#!/usr/bin/env python3
"""Compile the port's HTML templates into native Mojo, with escaping by default.

Only static source templates are input; database contents and HTTP responses are
never read by this compiler. No template interpreter runs in the server.
"""
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def q(s): return json.dumps(s, ensure_ascii=False)

def compile_one(name, source):
    source = re.sub(r'\s*({[{%#]-)', lambda m: m[1].replace('-', ''), source)
    source = re.sub(r'(-[%#}]})\s*', lambda m: m[1].replace('-', ''), source)
    source = re.sub(r'{#.*?#}', '', source, flags=re.S)
    lines = [f'def {name}(v: Dict[String, String]) raises -> String:', '    var out = String()']
    depth = 1
    def emit(line): lines.append('    '*depth+line)
    for token in re.split(r'({{.*?}}|{%.*?%})', source, flags=re.S):
        if token.startswith('{{'):
            expr = token[2:-2].strip()
            if expr.startswith('asset:'):
                value = f'asset({q(expr[6:])})'
            else:
                raw = expr.endswith('|safe')
                key = expr.removesuffix('|safe').strip()
                assert re.fullmatch(r'[\w.]+', key), (name,expr)
                value = f'v.get({q(key)}, "")'
                if not raw: value = f'escape({value})'
            emit(f'out += {value}')
        elif token.startswith('{%'):
            expr = token[2:-2].strip()
            if expr.startswith('if '):
                cond = expr[3:]
                cond = re.sub(r'[a-zA-Z_][\w.]*', lambda m: f'(v.get({q(m[0])}, "") == "1")', cond)
                cond = cond.replace('&&',' and ').replace('||',' or ').replace('!','not ')
                emit('if '+cond+':'); depth += 1
            elif expr == 'else':
                depth -= 1; emit('else:'); depth += 1
            elif expr == 'endif': depth -= 1
            else: raise ValueError((name,expr))
        elif token:
            # Split static HTML at line boundaries to keep generated code reviewable.
            for s in token.splitlines(keepends=True): emit(f'out += {q(s)}')
    assert depth == 1, name
    emit('return out^')
    return '\n'.join(lines)

manifest=json.loads((ROOT/'assets/manifest.json').read_text())
parts=['# Generated by tools/compile_templates.py; edit templates/*.html.', 'from text import escape', '',
       'def asset(name: String) raises -> String:']
for name, value in manifest.items():
    parts += [f'    if name == {q(name)}:', f'        return {q("/assets/"+value["digested_path"])}']
parts += ['    raise Error("Unknown asset: " + name)', '']
parts += ['def importmap() -> String:', '    return '+q((ROOT/'assets/importmap.html').read_text()), '']
css='\n'.join('<link rel="stylesheet" href="/assets/'+manifest[k]['digested_path']+'" data-turbo-track="reload" />' for k in sorted(manifest) if k.endswith('.css'))
parts += ['def stylesheets() -> String:', '    return '+q(css), '']
for path in sorted((ROOT/'templates').glob('*.html')):
    parts.append(compile_one(path.stem, path.read_text()))
    parts.append('')
(ROOT/'src/templates.mojo').write_text('\n'.join(parts))
