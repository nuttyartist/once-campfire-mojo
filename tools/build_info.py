#!/usr/bin/env python3
"""Generate safe, deterministic compile-time build identity."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def identity():
    version = (ROOT / "VERSION").read_text().strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+(?:-[a-z0-9.-]+)?", version):
        raise ValueError("VERSION must be a semantic version")
    revision = os.environ.get("GIT_REVISION", "")
    if not revision:
        result = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True)
        revision = result.stdout.strip() if result.returncode == 0 else "unknown"
    if revision != "unknown" and not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("GIT_REVISION must be a full lowercase commit hash or unknown")
    return {"version": version, "revision": revision}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    info = identity()
    if args.output:
        text = "# Generated by tools/build_info.py.\n" + "\n".join(f"comptime {key.upper()} = {json.dumps(value)}" for key, value in info.items()) + "\n"
        args.output.parent.mkdir(parents=True, exist_ok=True)
        if not args.output.exists() or args.output.read_text() != text:
            args.output.write_text(text)
    else:
        print(json.dumps(info))
